void GetFunName (int id, LPSTR Name)
{   
	SLONG	ID;  
	short	l,i,ncmd;  
	LPSTR	pSpace;

	*Name = 0;
	l=sizeof(GFCMDS);
	ncmd = l/32;
	for (i=0;i<ncmd;i++) 
	{   
		if ((pSpace = _fstrchr (GFCMDS[i],' ')))
			*pSpace = 0;
		else
			pSpace = _fstrchr (GFCMDS[i],0);
		pSpace++;
		ID = atol (pSpace);  
		if (ID == id) 
		{
			_fstrcpy (Name,GFCMDS[i]);
			return;
		} 
	}
	
	return;
}

SLONG ConvertCMDToNum (LPSTR CMD)
{
	SLONG	ID;  
	short	l,i,ncmd;  
	LPSTR	pSpace;
	
	if (!_fstrnicmp (CMD,"IDM_",4))
	{
		l=sizeof(IDMCMDS);
		ncmd = l/32;
		for (i=0;i<ncmd;i++) 
		{   
			if ((pSpace = _fstrchr (IDMCMDS[i],' ')))
				*pSpace = 0;
			else
				pSpace = _fstrchr (IDMCMDS[i],0);
			pSpace++;
			if (!_fstricmp (&CMD[4],IDMCMDS[i]))
			{ 
				ID = atol (pSpace);
				return ID;
			} 
		}
	}
	else if (!_fstrnicmp (CMD,"GF_",3))
	{ 
		l=sizeof(GFCMDS);
		ncmd = l/32;
		for (i=0;i<ncmd;i++) 
		{   
			if ((pSpace = _fstrchr (GFCMDS[i],' ')))
				*pSpace = 0;
			else
				pSpace = _fstrchr (GFCMDS[i],0);
			pSpace++;
			if (!_fstricmp (&CMD[3],GFCMDS[i]))
			{ 
				ID = -atol (pSpace);
				return ID;
			} 
		}
	}
	ID = atol(CMD);
	ID = -ID;   
	return ID;
}


